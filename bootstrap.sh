#!/usr/bin/env bash
# Bootstrap a one-person-company workspace.
#
# Copies the reusable "machine" into a target directory and fills in the
# per-project company files with empty templates.
#
#   bash bootstrap.sh [target-dir] [--force] [--check]
#
#   target-dir   where to create the workspace (default: current directory)
#   --force      overwrite an existing tooling/ and playbook/
#   --check      report what would happen, change nothing
#
# The machine (these files) is reusable across every project:
#   tooling/            the `opc` CLI
#   playbook/           the 12-document guide
#   company/AGENTS.md   the eight operating rules
#   company/research/   the four source-linked research briefs
#   examples/           the worked receipt-ledger example
#   package.json .gitignore
#
# Everything else under company/ is PER PROJECT and is generated by `opc init`:
#   company/charter.md  company/metrics.md  company/budget.md  company/roadmap.md
#   company/specs/      company/tasks/      company/decisions/  company/playbooks/
#   .agent/roles/       .agent/checklists/

set -euo pipefail

PLUGIN_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
TEMPLATE="$PLUGIN_DIR/template"

TARGET=""
FORCE=0
CHECK=0
for arg in "$@"; do
  case "$arg" in
    --force) FORCE=1 ;;
    --check) CHECK=1 ;;
    -h|--help) sed -n '2,30p' "${BASH_SOURCE[0]}"; exit 0 ;;
    *) TARGET="$arg" ;;
  esac
done
[ -z "$TARGET" ] && TARGET="$PWD"

mkdir -p "$TARGET"
TARGET="$(cd "$TARGET" && pwd)"

say() { printf '%s\n' "$*"; }
run() {
  if [ "$CHECK" -eq 1 ]; then say "  [check] $*"; else eval "$@"; fi
}

say ""
say "One-person-company bootstrap"
say "  template : $TEMPLATE"
say "  target   : $TARGET"
say ""

if [ ! -d "$TEMPLATE/tooling" ]; then
  say "ERROR: template/tooling is missing from $PLUGIN_DIR"
  exit 1
fi

# --- guard against clobbering an existing machine -------------------------
if [ -d "$TARGET/tooling" ] && [ "$FORCE" -ne 1 ]; then
  say "tooling/ already exists in the target."
  say "Re-run with --force to overwrite it, or pick a fresh directory."
  say ""
  say "If this workspace is already initialised, you probably want:"
  say "  cd \"$TARGET\" && node tooling/src/cli.mjs doctor"
  exit 1
fi

# --- copy the reusable machine -------------------------------------------
say "Copying the machine..."
for item in tooling playbook examples; do
  run "rm -rf \"\$TARGET/$item\""
  run "cp -R \"\$TEMPLATE/$item\" \"\$TARGET/$item\""
  say "  + $item/"
done
for item in package.json .gitignore; do
  run "cp \"\$TEMPLATE/$item\" \"\$TARGET/$item\""
  say "  + $item"
done

# --- merge the reusable company-level files ------------------------------
# Written one by one so an existing project's own files are never lost.
say "Merging company-level rules and research (existing files are kept)..."
mkdir -p "$TARGET/company" "$TARGET/company/research"
run "cp -n \"\$TEMPLATE/company/AGENTS.md\" \"\$TARGET/company/AGENTS.md\" 2>/dev/null || true"
for f in "$TEMPLATE/company/research/"*.md; do
  [ -e "$f" ] || continue
  run "cp -n \"\$f\" \"\$TARGET/company/research/\" 2>/dev/null || true"
done
say "  + company/AGENTS.md"
say "  + company/research/ (4 briefs)"

# --- fill in the per-project skeleton ------------------------------------
say "Generating the per-project company files..."
run "cd \"\$TARGET\" && node tooling/src/cli.mjs init"

# --- health check ---------------------------------------------------------
say ""
if [ "$CHECK" -eq 1 ]; then
  say "Check-only run — nothing was written."
  exit 0
fi

say "Health check:"
( cd "$TARGET" && node tooling/src/cli.mjs doctor ) || true

say ""
say "Workspace ready: $TARGET"
say ""
say "Next:"
say "  1. Edit company/charter.md — the first thing every agent reads."
say "  2. node tooling/src/cli.mjs new spec \"Your first feature\""
say "  3. node tooling/src/cli.mjs new task \"First slice\" \\"
say "       --spec company/specs/<file>.md --owner agent:engineer --writes \"apps/**\""
say "  4. node tooling/src/cli.mjs board --ready"
say "  5. node tooling/src/cli.mjs pack <TASK-ID>   # this output IS the agent prompt"
say ""
