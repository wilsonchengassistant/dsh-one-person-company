// Context pack: assemble exactly the material an agent needs to do one task —
// nothing more. This is the mechanism that keeps a one-person company's
// context cost bounded: an agent never loads the whole company, only its task,
// its spec, its charter, and the rules that apply to its write scope.

import { join } from 'node:path'
import { readdirSync } from 'node:fs'
import { read, exists, parseFrontmatter } from './util.mjs'
import { loadTasks, decorate } from './board.mjs'

export function buildContextPack(root, taskId, { roles = ['owner'] } = {}) {
  const tasks = decorate(loadTasks(root), root)
  const task = tasks.find((t) => t.id === taskId)
  if (!task) throw new Error(`Task not found: ${taskId}`)

  const parts = []
  parts.push(`# Context pack — ${task.id}: ${task.title}`)
  parts.push(`_Generated by \`opc pack ${task.id}\` on ${new Date().toISOString().slice(0, 10)}._`)
  parts.push('')

  // 1. Who you are and what the company is.
  const charterPath = join(root, 'company', 'charter.md')
  if (exists(charterPath)) {
    parts.push('## 1. Company charter (read fully)')
    parts.push(read(charterPath).trim())
    parts.push('')
  }

  // 2. The contract: the spec.
  if (task.spec) {
    const specPath = join(root, task.spec)
    if (task.specExists) {
      const { data, body } = parseFrontmatter(read(specPath))
      parts.push(`## 2. Spec — ${data.title || task.spec}`)
      parts.push(
        task.specApproved
          ? `_Spec status: ${task.specStatus}. Cleared to start._`
          : `_Spec status: ${task.specStatus}. **This spec is not approved. Say so and stop — do not start the work.**_`
      )
      parts.push('')
      parts.push(body.trim())
      parts.push('')
    } else {
      parts.push(`## 2. Spec — MISSING (${task.spec})`)
      parts.push('The spec referenced by this task does not exist. Ask the PM role for it.')
      parts.push('')
    }
  } else {
    parts.push('## 2. Spec — none linked')
    parts.push('This task has no spec. Do not start work: ask the PM role to write one.')
    parts.push('')
  }

  // 3. The task itself.
  const { data: taskData, body: taskBody } = parseFrontmatter(read(task.path))
  parts.push('## 3. The task')
  parts.push(read(task.path).trim())
  parts.push('')
  parts.push('### Dependencies')
  if ((task.deps || []).length) {
    for (const d of task.deps) {
      const dep = tasks.find((t) => t.id === d)
      parts.push(`- ${d} — ${dep ? `${dep.status}: ${dep.title || ''}` : 'MISSING'}`)
    }
  } else {
    parts.push('- none')
  }
  parts.push('')

  // 4. Your role charter (+ the reviewer's, so you know what will be checked).
  parts.push('## 4. Role charters')
  const roleFiles = listRoleFiles(root)
  const wanted = []
  for (const key of roles) {
    if (key === 'owner' && taskData.owner) wanted.push(roleName(taskData.owner))
    if (key === 'reviewer') wanted.push('reviewer')
    if (key === 'all') wanted.push(...roleFiles.map((r) => r.name))
  }
  for (const name of [...new Set(wanted.filter(Boolean))]) {
    const file = roleFiles.find((r) => r.name === name)
    if (!file) {
      parts.push(`### Role: ${name}`)
      parts.push(
        name === 'founder'
          ? 'This task is owned by the human founder. There is no agent charter for a human — the founder gates in section 7 are the operating rules.'
          : `No charter found for role "${name}". This owner cannot act until a charter exists at \`.agent/roles/${name}.md\`.`
      )
      parts.push('')
      continue
    }
    parts.push(`### Role: ${name}`)
    parts.push(read(file.path).trim())
    parts.push('')
  }

  // 5. The write scope you may touch.
  parts.push('## 5. Your write scope')
  parts.push(
    (taskData.writes && taskData.writes.length)
      ? (Array.isArray(taskData.writes) ? taskData.writes : [taskData.writes])
          .map((w) => `- \`${w}\``)
          .join('\n')
      : '- (not declared — declare it before editing anything)'
  )
  parts.push('')

  // 6. Definition of done.
  const donePath = join(root, '.agent', 'checklists', 'definition-of-done.md')
  if (exists(donePath)) {
    parts.push('## 6. Definition of done')
    parts.push(read(donePath).trim())
    parts.push('')
  }

  // 7. Operating rules.
  const rulesPath = join(root, 'company', 'AGENTS.md')
  if (exists(rulesPath)) {
    parts.push('## 7. Operating rules')
    parts.push(read(rulesPath).trim())
    parts.push('')
  }

  return parts.join('\n')
}

export function listRoleFiles(root) {
  const dir = join(root, '.agent', 'roles')
  if (!exists(dir)) return []
  return readdirSync(dir)
    .filter((f) => f.endsWith('.md'))
    .sort()
    .map((f) => ({ name: f.replace(/\.md$/, ''), path: join(dir, f) }))
}

function roleName(owner) {
  const s = String(owner)
  const m = /(?:agent|human):([a-z_-]+)/.exec(s)
  return m ? m[1] : null
}
